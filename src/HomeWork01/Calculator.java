package HomeWork01;

public class Calculator {
	
	public void add(int a, int b) {
		int result = a + b;
	}
	public void subtract(int a, int b) {
		int result = a - b;	
	}
	public void multiply(int a, int b) {
		int result = a * b;
	}
	public void divide(double a, int b) {
		double result = a / b;
	}
}
